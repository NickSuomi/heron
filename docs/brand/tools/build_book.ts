// ---- Write or check -------------------------------------------------------------------------------

const readme = withTable(readFileSync(readmePath, "utf8"))
const html = page(readme)
const isCheck = process.argv.includes("--check")
const stale = [
  [readmePath, readme],
  [pagePath, html],
].filter(([path, content]) => readFileSync(path ?? "", "utf8") !== content)

if (isCheck) {
  if (stale.length > 0) {
    console.error(`out of date: ${stale.map(([path]) => path).join(", ")}. Run node docs/brand/tools/build_book.ts`)
    process.exit(1)
  }
  console.log("design book is up to date")
} else {
  writeFileSync(readmePath, readme)
  writeFileSync(pagePath, html)
  console.log(`wrote ${readmePath} and ${pagePath}`)
}

const channel = (value: number): number => {
  const c = value / 255
  return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
}

const luminance = (hex: string): number => {
  const [r, g, b] = [1, 3, 5].map((at) => channel(Number.parseInt(hex.slice(at, at + 2), 16)))
  return 0.2126 * (r ?? 0) + 0.7152 * (g ?? 0) + 0.0722 * (b ?? 0)
}

const ratio = (a: string, b: string): number => {
  const [high, low] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return ((high ?? 0) + 0.05) / ((low ?? 0) + 0.05)
}

const grade = (value: number, rule: Pair[3]): string =>
  rule === "exempt" ? "exempt" : value >= 7 ? "AAA" : value >= 4.5 ? "AA" : "FAIL"

const contrastTable = (): string => {
  const rows = pairs.map(([use, text, background, rule]) => {
    const value = ratio(text, background)
    return `| ${use} | \`${text}\` | \`${background}\` | ${value.toFixed(2)} | ${grade(value, rule)} |`
  })
  return ["| Use | Text | Background | Ratio | WCAG |", "|---|---|---|---|---|", ...rows].join("\n")
}

const failing = pairs.filter(([, text, background, rule]) => rule === "text" && ratio(text, background) < 4.5)
if (failing.length > 0) {
  console.error(`contrast below AA: ${failing.map(([use]) => use).join(", ")}`)
  process.exit(1)
}

const start = "<!-- contrast-table:start (generated by docs/brand/tools/build_book.ts) -->"
const end = "<!-- contrast-table:end -->"

const withTable = (source: string): string => {
  const from = source.indexOf(start)
  const to = source.indexOf(end)
  if (from < 0 || to < from) throw new Error("README.md has lost its contrast-table markers")
  return `${source.slice(0, from + start.length)}\n\n${contrastTable()}\n\n${source.slice(to)}`
}

// ---- HTML -----------------------------------------------------------------------------------------

const escape = (text: string): string =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;")

const isColour = (text: string): boolean => /^#[0-9a-f]{6}$/i.test(text) || /^rgba?\([\d\s.,]+\)$/.test(text)

const inline = (parts: ReadonlyArray<Inline>): string =>
  parts
    .map((part) => {
      switch (part.kind) {
        case "text":
          return escape(part.text)
        case "code":
          return isColour(part.text)
            ? `<code><span class="swatch" style="background:${escape(part.text)}"></span>${escape(part.text)}</code>`
            : `<code>${escape(part.text)}</code>`
        case "strong":
          return `<strong>${escape(part.text)}</strong>`
        case "link":
          return `<a href="${escape(part.href)}">${escape(part.text)}</a>`
      }
    })
    .join("")

const block = (item: Block): string => {
  switch (item.kind) {
    case "heading":
      return `<h3>${inline(item.text)}</h3>`
    case "paragraph":
      return `<p>${inline(item.text)}</p>`
    case "list": {
      const tag = item.isOrdered ? "ol" : "ul"
      return `<${tag}>${item.items.map((each) => `<li>${inline(each)}</li>`).join("")}</${tag}>`
    }
    case "table":
      return `<div class="table"><table><thead><tr>${item.head.map((cell) => `<th>${inline(cell)}</th>`).join("")}</tr></thead><tbody>${item.rows
        .map((row) => `<tr>${row.map((cell) => `<td>${inline(cell)}</td>`).join("")}</tr>`)
        .join("")}</tbody></table></div>`
    case "code":
      return `<pre>${escape(item.text)}</pre>`
  }
}

